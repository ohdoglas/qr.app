export type Language = keyof typeof translations;
export type TranslationKey = keyof typeof translations.en;

export function translate(language: Language, key: TranslationKey, values: Record<string, string | number> = {}): string {
    const template = translations[language][key] ?? translations.en[key];
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
